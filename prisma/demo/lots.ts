// Date du jour décalée, à minuit UTC (colonnes @db.Date)
const dayOffset = (offset: number) => {
  const date = new Date();
  date.setUTCHours(0, 0, 0, 0);
  date.setUTCDate(date.getUTCDate() + offset);
  return date;
};

export async function seedDemoLots(prisma: PrismaClient, siteId: string) {
  for (const [position, lot] of DEMO_LOTS.entries()) {
    await prisma.lot.create({
      data: {
        siteId,
        position,
        key: lot.key,
        label: lot.label,
        description: lot.description,
        title: lot.title,
        subcontractor: lot.subcontractor,
        marketLabel: lot.marketLabel,
        marketAmount: lot.marketAmount,
        marketQuantity: lot.marketQuantity,
        unit: lot.unit,
        quantityLabel: lot.quantityLabel,
        deliveredLabel: lot.deliveredLabel,
        unitPrice: lot.unitPrice,
        remainingShipmentsNote: lot.remainingShipmentsNote ?? null,
        plans: {
          create: lot.plans.map(
            (
              [
                name,
                level,
                number,
                index,
                planned,
                actual,
                sent,
                from,
                to,
                status,
              ],
              planPosition,
            ) => ({
              name,
              level,
              number,
              index,
              planned,
              actual,
              sentDate: dayOffset(sent),
              deliveryFrom: dayOffset(from),
              deliveryTo: to === null ? null : dayOffset(to),
              status,
              position: planPosition,
            }),
          ),
        },
        shipments: {
          create: lot.shipments.map(([name, offset]) => ({
            name,
            plannedDate: dayOffset(offset),
          })),
        },
      },
    });
  }
}
